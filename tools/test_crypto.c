#include <stdio.h>
#include <string.h>
#include "sha256.h"
#include "aes.h"
#include "x25519.h"

static int eq(const uint8_t *a, const uint8_t *b, int n) {
    return memcmp(a, b, (size_t)n) == 0;
}

int main(void) {
    uint8_t dig[32];
    static const uint8_t abc_dig[32] = {
        0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde,
        0x5d, 0xae, 0x22, 0x23, 0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c,
        0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad};
    uint8_t key[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                       0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    uint8_t pt[16] = {0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
                      0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff};
    uint8_t expect[16] = {0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30,
                          0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a};
    uint8_t ct[16];
    uint8_t scalar[32] = {
        0xa5, 0x46, 0xe3, 0x6b, 0xf0, 0x52, 0x7c, 0x9d, 0x3b, 0x16, 0x15, 0x4b,
        0x82, 0x46, 0x5e, 0xdd, 0x62, 0x14, 0x4c, 0x0a, 0xc1, 0xfc, 0x5a, 0x18,
        0x50, 0x6a, 0x22, 0x44, 0xba, 0x44, 0x9a, 0xc4};
    uint8_t point[32] = {
        0xe6, 0xdb, 0x68, 0x67, 0x58, 0x30, 0x30, 0xdb, 0x35, 0x94, 0xc1, 0xa4,
        0x24, 0xb1, 0x5f, 0x7c, 0x72, 0x66, 0x24, 0xec, 0x26, 0xb3, 0x35, 0x3b,
        0x10, 0xa9, 0x03, 0xa6, 0xd0, 0xab, 0x1c, 0x4c};
    uint8_t xout[32];
    static const uint8_t xexp[32] = {
        0xc3, 0xda, 0x55, 0x37, 0x9d, 0xe9, 0xc6, 0x90, 0x8e, 0x94, 0xea, 0x4d,
        0xf2, 0x8d, 0x08, 0x4f, 0x32, 0xec, 0xcf, 0x03, 0x49, 0x1c, 0x71, 0xf7,
        0x54, 0xb4, 0x07, 0x55, 0x77, 0xa2, 0x85, 0x52};
    sha256((const uint8_t *)"abc", 3, dig);
    if (!eq(dig, abc_dig, 32)) {
        fprintf(stderr, "sha256 abc mismatch\n");
        return 1;
    }
    aes128_encrypt(key, pt, ct);
    if (!eq(ct, expect, 16)) {
        fprintf(stderr, "aes mismatch\n");
        return 1;
    }
    x25519(xout, scalar, point);
    if (!eq(xout, xexp, 32)) {
        int i;
        fprintf(stderr, "x25519 mismatch\n");
        for (i = 0; i < 32; ++i)
            fprintf(stderr, "%02x", xout[i]);
        fprintf(stderr, "\n");
        return 1;
    }
    printf("crypto ok\n");
    return 0;
}
